package org.myorg.payments

import kotlinx.serialization.Serializable

/** One side of a payment: where the money comes from or goes to. */
@Serializable
data class Party(
    /** `checking` for the source; `card` or `bank` for the destination. */
    val kind: String,
    val account: String,
) {
    companion object {
        const val CHECKING = "checking"
        const val CARD = "card"
        const val BANK = "bank"
    }
}

/**
 * The payment's state, carried by every payment event (event-carried state transfer).
 * Facts about one step, such as why it failed, go on the event, never here.
 */
@Serializable
data class Payment(
    /** Generated by the client (`PUT /payments/{id}`). */
    val id: String,
    /** From the caller's identity, never from the request body. */
    val customerId: String,
    val from: Party,
    val to: Party,
    /** A decimal as a string with two decimals, e.g. "100.00". Never a binary floating-point number. */
    val amount: String,
    /** ISO 4217 code. */
    val currency: String,
    /** Epoch ms. */
    val submittedAt: Long,
)

/** Reference data about an account, as the payments subsystem needs it. */
@Serializable
data class Account(
    val number: String,
    val kind: String,
    val customerId: String,
    /** `open` or `closed`. */
    val status: String,
) {
    companion object {
        const val OPEN = "open"
        const val CLOSED = "closed"
    }
}

/** Why a step or a payment failed. Data, not types, so lower kebab case. */
object Reasons {
    const val INSUFFICIENT_FUNDS = "insufficient-funds"
    const val ACCOUNT_CLOSED = "account-closed"
    const val ACCOUNT_NOT_FOUND = "account-not-found"
    const val REJECTED = "rejected"

    val ALL = setOf(INSUFFICIENT_FUNDS, ACCOUNT_CLOSED, ACCOUNT_NOT_FOUND, REJECTED)
}
